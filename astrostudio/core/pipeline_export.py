"""Export recorded CLI jobs as reproducible scripts."""

import shlex
from typing import Dict, Iterable, List


def cli_entries(entries: Iterable[Dict], session: str = None) -> List[List[str]]:
    result = []
    for entry in entries:
        if entry.get("event") != "cli_start":
            continue
        if session and entry.get("session") != session:
            continue
        argv = entry.get("argv") or []
        if argv:
            result.append(list(argv))
    return result


def write_shell(argv_list: List[List[str]], path: str) -> None:
    lines = ["#!/usr/bin/env bash", "set -euo pipefail", ""]
    lines.extend(" ".join(shlex.quote(token) for token in argv) for argv in argv_list)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def write_makefile(argv_list: List[List[str]], path: str) -> None:
    lines = ["# Generated by Astro Studio from serialized argv", "SHELL := /bin/bash", "", "all:"]
    if not argv_list:
        lines.append("\t@echo 'No recorded jobs'")
    for index, argv in enumerate(argv_list):
        target = "job-%03d" % index
        lines.extend([target + ":", "\t" + " ".join(shlex.quote(token) for token in argv), ""])
    lines.append("all: " + " ".join("job-%03d" % i for i in range(len(argv_list))))
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
